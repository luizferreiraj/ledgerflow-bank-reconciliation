"""An excerpt of the end-to-end suite: the deduplication, re-import, refused-batch and re-export
tests with every fixture and helper they use; the first-import, refused-statement, fixed-width
layout and rewritten-description tests are left out.

From PDF to export batch, on the synthetic statement: the guarantees the UI does not loosen.

These tests used to run against a client's statements and chart of accounts, and they left the
public suite along with them. They come back here on top of `synthetic_statement`: the same PDF that
`tests/test_synthetic_statement.py` proves closes at 0.00, now coming in through the workbench
import, getting classified, and turning into a batch file.

What this excerpt proves, in the order the accountant goes through it:

- re-importing does not duplicate: neither the same file, nor the same statement downloaded again,
  which only the SQLite `UNIQUE` constraint catches (see ADR 4);
- when the READING of the same file improves, the text is corrected in place, with no duplicate and
  no lost classification;
- the batch is refused WHOLE if a single entry has no account, and it does not go out twice without
  confirmation (see ADR 8).

Everything goes through the real APIs: `importing`, `repository`, the UI routes through
`TestClient`, and `exporting.generate`. The batch is generated by `exporting.generate` rather than
through its route, because the route writes to the output directory next to the default database,
outside `tmp_path`.

Chart-of-accounts names, category names and statement descriptions stay in Portuguese: they are the
data a Brazilian bank and accounting system print, and they flow into the batch as they are. Route
paths and form fields are those of the workbench's HTTP API.
"""

