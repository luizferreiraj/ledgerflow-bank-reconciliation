def pdf(tmp_path, statement=None, lines=None, label="sicoob-sisbr-2026-06.pdf") -> bytes:
    return write_pdf(tmp_path / label, statement or june_statement(), lines).read_bytes()


def run_import(cx, company, content, label="sicoob-sisbr-2026-06.pdf"):
    return importing.import_file(cx, company, label, content)


def entries(cx, company):
    return repo.entries(cx, company, PERIOD)


# --------------------------------------------------------------- re-importing


def test_reimporting_the_same_file_creates_no_entry(cx, company, tmp_path):
    """The same file (same hash) again: zero new entries."""
    content = pdf(tmp_path)
    first_import = run_import(cx, company, content)
    second = run_import(cx, company, content)

    assert (first_import.new_entries, first_import.duplicates) == (7, 0)
    assert second.accepted
    assert (second.new_entries, second.duplicates, second.corrected) == (0, 7, 0)
    assert repo.summary(cx, company, PERIOD)["total"] == 7


def test_same_statement_downloaded_again_does_not_duplicate(cx, company, tmp_path):
    """The case that only the database's `UNIQUE` constraint catches.

    The client downloads the June statement twice. The transactions are the same, but the bank
    stamps the time of issue, so the BYTES differ, and the "same file" shortcut (a lookup by
    content hash) does not recognize the second one. It goes on as a new statement all the way to
    `INSERT OR IGNORE`, and it is the schema's `UNIQUE (bank_account_id, identity)` that refuses
    each of the seven entries.

    Both statements are recorded as accepted: that is the proof that the second one went through
    the write path, and not through the shortcut.
    """
    morning = pdf(tmp_path, label="june-morning.pdf")
    afternoon = pdf(
        tmp_path,
        june_statement(issued_at=datetime(2026, 7, 1, 17, 45)),
        label="june-afternoon.pdf",
    )
    assert morning != afternoon, "without different bytes the test would hit the hash shortcut"

    run_import(cx, company, morning, "june-morning.pdf")
    second = run_import(cx, company, afternoon, "june-afternoon.pdf")

    assert second.accepted
    assert (second.new_entries, second.duplicates) == (0, 7)
    assert repo.summary(cx, company, PERIOD)["total"] == 7
    assert [e["accepted"] for e in repo.statements(cx, company)] == [1, 1]


def test_reimport_with_corrected_text_neither_duplicates_nor_loses_classification(
    cx, company, tmp_path, monkeypatch
):
    """When the READING improves, the same file yields different text.

    The description is part of the dedup identity, so a corrected text looks like a new entry, and
    re-importing would duplicate it. The first import simulates the old reading, with a defect the
    column parser documents: the first word of the description got lost, and `PIX RECEB.OUTRA IF`
    became `RECEB.OUTRA IF`. The money is the same; the file closes under both readings.

    The accountant classifies everything and rewrites the description of one entry. Re-importing
    with the correct reading fixes the text IN PLACE: nothing new, nothing duplicated, and the
    category, the account and the accountant's own text all intact.

    And the identity follows the text: the same statement, downloaded again after the fix, still
    does not duplicate. Without that, the corrected `PIX` would look "new" to the `UNIQUE`
    constraint on the next import.
    """
    from statement import pipeline

    correct_reading = pipeline.extract_pages

    def old_reading(pathname):
        pages = correct_reading(pathname)
        pix_line_tops = {p.top for page in pages for p in page if p.string == "RECEB.OUTRA"}
        return [
            [p for p in page if not (p.string == "PIX" and p.top in pix_line_tops)]
            for page in pages
        ]

    content = pdf(tmp_path)
    with monkeypatch.context() as before_fix:
        before_fix.setattr(pipeline, "extract_pages", old_reading)
        first_import = run_import(cx, company, content)
    assert first_import.accepted and first_import.new_entries == 7
    (target,) = [l for l in entries(cx, company) if l["description"] == "RECEB.OUTRA IF"]

    customers = repo.create_category(cx, company, "CLIENTES", "112-7")
    for line in entries(cx, company):
        repo.classify(cx, line["id"], customers, "112-7", None)
    repo.edit_description(cx, target["id"], "RECEBIMENTO DISTRIBUIDORA NORTE")

    second = run_import(cx, company, content)

    assert second.accepted
    assert (second.new_entries, second.duplicates, second.corrected) == (0, 7, 1)
    summary = repo.summary(cx, company, PERIOD)
    assert (summary["total"], summary["classified"]) == (7, 7)
    corrected_entry = repo.one_entry(cx, target["id"])
    assert corrected_entry["description"] == "PIX RECEB.OUTRA IF"
    assert corrected_entry["category_id"] == customers
    assert corrected_entry["ledger_account"] == "112-7"
    assert corrected_entry["edited_description"] == "RECEBIMENTO DISTRIBUIDORA NORTE"

    downloaded_again = pdf(
        tmp_path, june_statement(issued_at=datetime(2026, 7, 2, 9, 0)), label="again.pdf"
    )
    third = run_import(cx, company, downloaded_again, "again.pdf")
    assert (third.new_entries, third.duplicates) == (0, 7)
    assert repo.summary(cx, company, PERIOD)["total"] == 7


