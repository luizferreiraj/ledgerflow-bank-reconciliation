def upload_chart_of_accounts(client, company, tmp_path):
    """The chart of accounts comes in the way the accountant uploads it: an XLSX exported from the
    accounting system."""
    import openpyxl

    workbook = openpyxl.Workbook()
    workbook.active.append(["Classificação", "Código", "Descrição"])
    for line in CHART_OF_ACCOUNTS:
        workbook.active.append(list(line))
    pathname = tmp_path / "chart-of-accounts-metalurgica.xlsx"
    workbook.save(pathname)
    with open(pathname, "rb") as file:
        response = client.post(
            f"/api/companies/{company}/chart-of-accounts",
            files={"file": (pathname.name, file, "application/octet-stream")},
        )
    assert response.json() == {"accounts": 5}, response.text


def prepare(cx, company, tmp_path, leave_out=()):
    """Imports, links the bank account to the chart of accounts, and classifies through the UI.

    `leave_out` holds descriptions that stay unclassified.
    """
    client = TestClient(app.create_app(cx))
    upload_chart_of_accounts(client, company, tmp_path)
    assert run_import(cx, company, pdf(tmp_path)).accepted

    (account,) = repo.bank_accounts(cx, company)
    client.post(f"/api/bank-accounts/{account['id']}", data={"code": BANK_LEDGER_CODE})
    categories = {
        code: client.post(
            f"/api/companies/{company}/categories/from-chart", data={"code": code}
        ).json()["id"]
        for code in set(CLASSIFICATION.values())
    }
    for line in entries(cx, company):
        if line["description"] in leave_out:
            continue
        code = CLASSIFICATION[line["description"]]
        response = client.post(
            f"/api/entries/{line['id']}",
            data={"category_id": categories[code], "ledger_account": code},
        )
        assert response.json()["ok"], response.text
    return client


@pytest.mark.parametrize("scenario", ["no_category", "category_without_account"])
def test_one_entry_without_account_refuses_the_whole_batch(cx, company, tmp_path, scenario):
    """A partial batch in the accounting system is worse than no batch at all.

    Six entries are ready and the bank fee has no account: either it was forgotten, or it went into
    a category created without a code. Not a byte is written, nothing goes into the export record,
    and the diagnostic points to the line. Once the fee is classified, the same batch goes out: it
    was the fee, and only the fee, that held it back.
    """
    prepare(cx, company, tmp_path, leave_out={"TARIFA COBRANÇA"})
    (fee,) = [l for l in entries(cx, company) if l["description"] == "TARIFA COBRANÇA"]
    if scenario == "category_without_account":
        no_code_category = repo.create_category(cx, company, "DESPESAS A CLASSIFICAR")
        repo.classify(cx, fee["id"], no_code_category, None, None)
    destination, record = tmp_path / "batch.txt", tmp_path / "exported_batches.jsonl"

    assert exporting.readiness(cx, company, PERIOD)["ready"] is False
    result, content = exporting.generate(cx, company, PERIOD, destination, record=record)

    assert result.generated is False
    assert content is None
    assert not destination.exists(), "not even a partial file"
    assert not record.exists(), "a refusal leaves no export trace"
    (problem,) = result.diagnostics
    assert problem.code == "MISSING_ACCOUNT"
    assert "TARIFA COBRAN" in problem.message

    fees = repo.create_category(cx, company, "TARIFAS BANCARIAS", "427-3")
    repo.classify(cx, fee["id"], fees, "427-3", None)
    result, content = exporting.generate(cx, company, PERIOD, destination, record=record)
    assert result.generated and result.entry_count == 7


def test_reexporting_the_same_period_requires_confirmation(cx, company, tmp_path):
    """The batch is a one-way street.

    Importing the same file twice into the accounting system duplicates everything at the
    destination, and identical content does not change that. The second generation is refused
    without touching the file that already exists; once confirmed, it comes out byte for byte the
    same and is marked as a regeneration in the export record.
    """
    prepare(cx, company, tmp_path)
    destination, record = tmp_path / "batch.txt", tmp_path / "exported_batches.jsonl"

    first, content = exporting.generate(cx, company, PERIOD, destination, record=record)
    assert first.generated

    again, nothing = exporting.generate(cx, company, PERIOD, destination, record=record)
    assert again.generated is False and nothing is None
    (notice,) = again.diagnostics
    assert notice.code == "PERIOD_ALREADY_EXPORTED"
    assert notice.details["content_changed"] == "False"
    assert destination.read_bytes() == content

    confirmed, regenerated = exporting.generate(
        cx, company, PERIOD, destination, confirm_regeneration=True, record=record
    )
    assert confirmed.generated and confirmed.regeneration
    assert regenerated == content, "same input, same bytes"
    assert [e.regeneration for e in read_export_record(record)] == [False, True]
